// @ts-check
/**
 * Compare every official record with the frozen legacy scrape and write
 * docs/data/CROSSCHECK.md. Informational: it never changes data and always exits 0.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { loadDataset } from '../src/lib/dataset.js'

const ROOT = join(import.meta.dirname, '..')
const official = loadDataset({ officialDir: join(ROOT, 'data', 'bulletins') })
const LEGACY_DIR = join(ROOT, 'data', 'visa-bulletins')
/** @type {Record<string, string>} */
const AREA = { allChargeabilityAreasExceptThoseListed: 'all', chinaMainlandBorn: 'china', india: 'india', mexico: 'mexico', philippines: 'philippines' }
/** @type {Record<string, string>} */
const CATEGORY = { otherWorkers: 'EB3OW', certainReligiousWorkers: 'EB4SR' }

const rows = []
const details = []
const totals = { same: 0, different: 0, legacyOnly: 0, legacyMissing: 0 }
for (const period of official.periods) {
  const record = official.get(period)
  const legacyPath = join(LEGACY_DIR, period.slice(0, 4), `${period}.json`)
  if (!record || !existsSync(legacyPath)) { totals.legacyMissing += 1; continue }
  const legacy = JSON.parse(readFileSync(legacyPath, 'utf8'))
  let same = 0
  let legacyOnly = 0
  const differences = []
  for (const [group, items] of Object.entries(legacy.categories ?? {})) {
    for (const [code, item] of Object.entries(/** @type {Record<string, any>} */ (items))) {
      for (const chart of /** @type {const} */ (['finalActionDates', 'datesForFiling'])) {
        for (const [legacyArea, value] of Object.entries(item[chart] ?? {})) {
          const area = AREA[legacyArea]
          const cells = /** @type {any} */ (record.categories)[group]?.[CATEGORY[code] ?? code]?.[chart]
          const officialValue = cells?.[area] ?? cells?.all
          if (officialValue === undefined) legacyOnly += 1
          else if (officialValue === value) same += 1
          else differences.push(`| ${code} | ${area} | ${chart === 'finalActionDates' ? 'Final Action' : 'Filing'} | ${value} | ${officialValue} |`)
        }
      }
    }
  }
  totals.same += same
  totals.different += differences.length
  totals.legacyOnly += legacyOnly
  rows.push(`| ${period} | ${same} | ${differences.length} | ${legacyOnly} |`)
  if (differences.length) {
    details.push(`### ${period}\n| Legacy row | Area | Chart | Legacy value | Official value |\n|---|---|---|---|---|\n${differences.join('\n')}`)
  }
}

const report = `# Cross-check: official records vs the frozen legacy scrape
Generated by \`npm run data:crosscheck\`. Official = parsed from the State Department page pinned in
\`data/sources/manifest.json\`. Legacy = \`data/visa-bulletins/\` (third-party compilation, never edited).
"Legacy only" counts cells the legacy file has but the official page does not list (for example Dates for
Filing before October 2015, or a column the bulletin did not print).

**Totals over ${rows.length} compared month(s): ${totals.same} matching cells, ${totals.different} different, ${totals.legacyOnly} legacy-only.**

| Period | Matching | Different | Legacy only |
|---|---|---|---|
${rows.join('\n')}

## Differences (official value wins)
${details.length ? details.join('\n\n') : 'None.'}
`
mkdirSync(join(ROOT, 'docs', 'data'), { recursive: true })
writeFileSync(join(ROOT, 'docs', 'data', 'CROSSCHECK.md'), report)
console.log(`Cross-check: ${rows.length} month(s), ${totals.same} matching, ${totals.different} different, ${totals.legacyOnly} legacy-only → docs/data/CROSSCHECK.md`)
